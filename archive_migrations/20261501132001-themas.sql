## Введение

### Значение защиты от шума

Увеличивающиеся шумовые воздействия снаружи и повышенные шумовые воздействия изнутри дома заставляют строителей все больше внимания уделять защите от шума.

Причинами растущего внимания к защите от шума являются:
- большие транспортные потоки;
- увеличивающееся авиационное сообщение;
- небольшие участки под строительство;
- более плотная застройка;
- различное время работы членов семьи;
- работа в разные смены и, соответственно, разное время сна и отдыха;
- большая нагрузка на человека на рабочем месте от шума машин и механизмов и как следствие, большая потребность в покое;
- более мощные стереоустановки;
- различные привычки относительно громкости телевизоров и аудиосистем;
- большая мощность домашних электроприборов.

Все эти шумовые воздействия делают людей более чувствительными.

Мероприятия по защите от шума в большинстве случаев не могут проводиться после постройки дома без учета его конструктива. Часто они касаются основных вопросов проектирования и строительства зданий.

### Звук

Звук - механические колебания упругого тела в частотном диапазоне слышимости человека.
Частота – число колебаний в секунду.

Взрослый человек с еще не поврежденным слухом воспринимает часто¬ты от 16 до 16000 Герц (Гц). Более молодой человек с нормальным слухом может различать звуки частотой до 20000 Гц, маленькие дети - до 24000 Гц, тогда как пожилые люди имеют намного меньший диапазон слышимости.

Низкие частоты находятся в диапазоне до 300 Гц.
Средние частоты - в диапазоне от 300 Гц до 800 Гц.
Высокие - начинаются от 800 Гц.

Звуковое давление - колебание воздуха, создаваемое давлением. Это происходит потому, что импульс передается на молекулы воздуха, а от них - на следующие молекулы воздуха. Таким образом возникают попеременно зоны разрежения и уплотнения воздуха. При этом возникает звуковое давление, которое в нашем ухе вызывает ощущение звука.

Громкость звука - величина, характеризующая слуховое ощущение для данного звука. Громкость звука сложным образом зависит от звукового давления (или интенсивности звука), частоты и формы колебаний.

Наше ухо воспринимает силу звука специфическим образом. Например, звук самолета и звук голоса отличаются по силе создаваемого давления в миллионы раз. Поэтому для удобства Александр Бэл разделил весь слышимый спектр звука на 13 частей. Числовая разница небольшая, но нужно понимать, что по силе давления они отличаются в тысячи раз. Это значение отвечает на вопрос “во сколько раз звук громче”, а не “насколько звук громче”.

Это утверждение можно проиллюстрировать следующими цифрами:
- +10 дБ = громкость х2;
- +20 дБ = громкость х4;
- +40 дБ = громкость х16 и так далее.

Значение 6 дБ может составлять разницу мощности звука в 2 раза в зависимости от частоты (в диапазоне средних частот, которые мы больше всего воспринимаем). Низкие частоты воспринимаются меньше чем высокие. Что бы услышать низкие частоты, нужен больший уровень звука.

