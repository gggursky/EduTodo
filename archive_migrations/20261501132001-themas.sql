## Строительная акустика

Строительная акустика - научная дисциплина, изучающая вопросы защиты помещений, зданий и территорий населённых мест от шума архитектурно-планировочными и строительно-акустическими (конструктивными) методами. Строительную акустику рассматривают и как отрасль прикладной акустики, и как раздел строительной физики.

К архитектурно-планировочным методам строительной акустики относятся: рациональные (с точки зрения защиты от шума) объёмно-планировочные решения зданий и помещений; удаление источников шума от защищаемых объектов; оптимальная планировка микрорайонов, жилых районов, а также территорий промышленных предприятий.

### Задачи строительной акустики

- расчет требуемой звукоизоляции наружных и внутренних ограждающих конструкций зданий и сооружений в зависимости от уровней действующего шума: расчет и проектирование звукоизоляции стен, перегородок в здании от воздушного шума; расчет и проектирование звукоизоляции междуэтажных перекрытий от воздушного и ударного шумов; расчет и проектирование конструкции оконных блоков в зависимости от уровня транспортного шума вблизи проектируемого или существующего здания;
- расчет снижения шума и вибрации от вентиляционных, насосных и других агрегатов и проектирование средств защиты (глушители шума, звукопоглощающие облицовки, кожухи, виброизоляторы и т. п.);
- архитектурно-акустическое проектирование залов различного назначения (залы театров и кинотеатров, теле- и радиостудии, студии звукозаписи, помещения для установки домашних кинотеатров).

Нормы допустимого шума на территориях и в помещениях зданий различного назначения должны соответствовать СП 51.13330.2011.

