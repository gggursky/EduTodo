1. **Высокая поверхностная плотность отражающих материалов**
   Не менее **950 кг/м³**
   (например, комбинация **Aku-line** и **Саундлайн-dB**)
— для эффективного отражения звука.

2. **Наличие звукопоглощающего слоя**
   Плотность **30–50 кг/м³**, классы поглощения **A, B**
