## Пути распространения шума

- **прямые пути** – это способ передачи звука в соседнее помещение через смежные поверхности, окна. Как правило, воздушный шум в большей степени имеет только прямые пути передачи звука;
- **косвенные пути** – это способ передачи звука через несущие и конструктивные элементы здания, а также щели и отверстия. Распространение вибраций чаще всего подразумевает их распространение через косвенные пути передачи звука.

