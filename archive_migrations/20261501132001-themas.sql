## Бескаркасная звукоизоляция

В основном это:
- композитные материалы, слои которых склеены между собой;
- листовые материалы, которые крепятся к стене без каркаса.

По большому счету, бескаркасные системы должны включать:
- звукопоглощающие слои;
- звукоотражающие слои.

---

### Особенности бескаркасных систем (ЗИПС)

В бескаркасной системе (сэндвич-панелях **ЗИПС**) уже присутствуют:
- отражающий слой — **ГВЛ**;
- поглощающий слой — **минераловатная плита**.

Однако такие системы обязательно необходимо:
- дополнительно зашивать листом гипсокартона **ГКЛА Aku-line**
для:
- увеличения массы конструкции;
- защиты виброизолирующих узлов.

Бескаркасные системы:
- примыкают к ограждающим конструкциям через виброизолирующую прокладку **Вибростек-М**;
- крепятся с помощью виброизолирующих креплений (виброизолирующих узлов).

---

## Демпферные ленты. Особенности

Необходимо использовать ленты на основе волокнистых материалов по следующим причинам:
- со временем структура не разрушается и материал не проседает, а значит эффективность не снижается;
- вспененные подложки быстро сминаются и перестают быть эффективными с точки зрения звукоизоляции, хотя для простых отделочных работ они подходят.

**Отсутствие вибропрокладок** может привести к тому, что:
- звук по металлу и бетону из-за жесткого примыкания будет передаваться на звукоизоляционную конструкцию;
- общая эффективность звукоизоляции снизится.

---

## Нюансы технологии звукоизоляции

Независимо от типа системы (каркасная или бескаркасная), облицовка должна быть **герметичной**.

Это означает:
- отсутствие щелей и отверстий;
- герметизацию всех стыков и зазоров.

Для этого используется:
- силиконовый эластичный герметик **Вибросил** с высокой адгезией к строительным материалам облицовки.

---

