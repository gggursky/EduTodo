## Каркасная звукоизоляция

### Материалы, используемые в каркасных звукоизоляционных системах

#### Какой поглощающий материал мы используем?

**Поглощающий слой:**
В жилых помещениях чаще всего используется **Шуманет-ЭКО** — это акустическая белая звукопоглощающая плита из штапельного волокна на акриловом связующем (это не обычная стекловата и не минвата!!!).

Материал:
- абсолютно экологически чистый;
- подобран специально для внутренней отделки.

Помимо плит **Шуманет-ЭКО** существуют другие звукопоглощающие плиты линейки **Шуманет**, например:
- **Шуманет-БМ** — минераловатная плита на основе базальта.

**Шуманет-БМ / Шуманет-ЭКО** — это основной поглощающий материал для каркасных облицовок.
Его задача — гасить переотражения и гул внутри конструкции.

Еще одним преимуществом данного материала является то, что он:
- не садится;
- не осыпается с течением времени
ввиду специальной технологии производства.

---

#### Какой отражающий материал мы используем?

Для обшивки каркаса используются плотные листовые материалы, которые могут быть специализированными, например:
- листы акустического гипсокартона **Aku-line**;
- листы **Саундлайн-dB**.

Данные слои играют роль отражения звука.
Чем их больше, тем массивнее получается преграда и тем меньше проходит звук.

Минимальное количество слоев таких материалов — **два**, по следующим причинам:
1. обеспечение необходимой массы конструкции;
2. перекрытие швов и стыков, через которые может проходить звук.

---

#### Можно ли использовать любые минераловатные плиты или пенопласт для заполнения каркаса?

**Нет**, любые минеральные плиты или пенопласт использовать нельзя.

Причины:
- необходима максимальная эффективность звукопоглощения;
- материал должен иметь:
  - плотность **30–50 кг/м³**;
- структуру с **открытыми порами**.

Например:
- пенопласт с закрытой структурой пор плохо поглощает звук;
- из-за жесткой структуры он может работать как резонатор и ухудшать звукоизоляцию.

В случае, когда в гипсокартонной облицовке применяется пенопласт, может создаваться эффект снижения шума, но:
- реальный эффект возникает за счет отражения звука гипсокартоном;
- пенопласт не поглощает звук, а наоборот — резонирует.

---

#### Играет ли роль способ крепления каркаса?

**Конечно, играет.**

Немаловажным является крепление звукоизоляции к примыкающим поверхностям помещения.

При монтаже звукоизоляционных конструкций важно:
- отсутствие жестких связей с изолируемыми поверхностями.

Крепление к потолку или стенам должно осуществляться:
- через виброизолирующие подвесы **Виброфлекс** (стеновые и потолочные).

Все места примыкания выполняются:
- через виброизолирующие элементы.

По периметру звукоизоляционных облицовок стен и потолка необходимо использовать:
- демпферную прокладку **Вибростек-М**
  (лента из синтетического волокна волокнистой структуры).

---

#### Можно ли крепить профили через жесткие подвесы и крепления?

**Ни в коем случае.**

Не должно быть никаких жестких связей, так как:
- они образуют звуковые мостики;
- снижают звукоизоляцию.

В используемой технологии применяются:
- специальные крепления **Виброфлекс** с упругими эластомерными прокладками.

