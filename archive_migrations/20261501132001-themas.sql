## Акустический словарь

**Допустимый уровень шума** – это уровень, который не вызывает у человека значительного беспокойства и существенных изменений показателей функционального состояния систем и анализаторов его организма, чувствительных к шуму.

**Звуковая мощность (Вт)** – это количество энергии, излучаемой источником шума в единицу времени.

**Изоляция воздушного шума (звукоизоляция) (R, дБ)** – это способность ограждающей конструкции уменьшать проходящий через нее звук.

**Изоляция ударного шума перекрытием** – это величина, характеризующая снижение ударного шума перекрытием.

**Индекс изоляции воздушного шума (Rw, дБ)** – это величина, служащая для оценки одним числом изоляции воздушного шума ограждающей конструкцией.

**Индекс приведенного уровня ударного шума (Lnw, дБ)** – это величина, служащая для оценки одним числом изоляции ударного шума перекрытием.

**Спектр шума** – разделение шума на его частотные составляющие по всему диапазону, воспринимаемому ухом человека.

**Октавные полосы частот** – 63, 125, 250, 500, 1000, 2000, 4000, 8000 Гц.

**Звукопоглощение** – это снижение энергии отражённой звуковой волны при взаимодействии с преградой.

**Коэффициент звукопоглощения (α)** – это отношение величины неотраженной поверхности к величине падающей энергии.

**Реверберация** – многократное отражение звука от ограждающих поверхностей помещения.

**Виброизоляция** – любая техническая мера, предпринимаемая для снижения переноса вибросилы от её источника.

**Закон массы** – зависимость изоляции воздушного шума от поверхностной массы преграды.

