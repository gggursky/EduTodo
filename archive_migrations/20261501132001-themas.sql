## Строительная терминология

**Облицовка** – покрытие поверхностей конструктивных элементов зданий и сооружений, выполненное из природных или искусственных материалов, которые отличаются высокими защитными (тепло-, звукоизоляционными) и декоративными качествами.

**Стена** – вертикальная строительная конструкция, которая ограничивает или разделяет пространство и, как правило, выполняет несущую или опорную функцию.

**Перегородка** – внутренняя вертикальная самонесущая строительная конструкция, разделяющая пространство.

**Каркасная перегородка** - перегородка, состоящая из плоской рамы на сплошном основании с наружным покрытием или заполнением.

**Перекрытие** – плоская горизонтальная строительная конструкция, которая выполняет функцию несущей конструкции пола.

**Пол** – конструкция, включающая конструктивные слои различного функционального назначения, выполненные из различных строительных материалов, по плите перекрытия или грунтовому основанию.

**"Плавающий" пол** - многослойная конструкция напольного покрытия, при устройстве которой отсутствует жесткая связь с базовой конструкцией здания (основание пола, плиты перекрытия, стены).

**Потолок** – нижняя часть плиты перекрытия, ограничивающая помещение сверху.

**Сухое и мокрое строительство.**
«Сухое» строительство предполагает комплекс строительных работ по устройству и облицовке строительных конструкций, в процессе которых исключены мокрые процессы с применением штукатурных, кладочных растворов, гипсовых и цементных смесей.

**Каркас** – несущая внутренняя или внешняя конструкция здания. Каркас призван выдерживать нагрузки, обеспечивать прочность и устойчивость объекта. В каркасных конструкциях несущие и ограждающие функции разделены между элементами.

