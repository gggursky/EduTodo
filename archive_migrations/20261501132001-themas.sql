## Виды шума и их особенность

### Воздушный шум
Воздушный шум – шум, излучаемый источником звуковых колебаний непосредственно в воздух. Примерами воздушного шума являются речь людей, работа радио и телеприёмников, игра на музыкальных инструментах. Воздушный шум возникает в воздухе и распространяется по нему. Звук от источника через воздух попадает на ограждающую конструкцию, заставляя ее, в свою очередь, колебаться и переизлучать шум в соседнее помещение. Источниками воздушного шума в быту чаще всего являются телевизор, громкие голоса, громкая музыка, лай собак и т.д.

### Ударный шум
Ударный шум – это шум, возникающий в результате падения тяжелых предметов на пол, стук каблуков, прыжки детей. Ударный шум возникает при механическом воздействии на строительные конструкции, при ударах о пол тяжелых предметов, перемещении мебели, перемещении людей, ударах по стене. По конструкциям звуковые колебания могут распространяться достаточно далеко в виде структурного шума.

### Структурный шум
Структурный шум – шум от удалённых источников, передаваемый в помещение за счёт вибраций несущих и ограждающих конструкций здания в целом. Примеры – шум лифтового и инженерного оборудования, работа перфоратора или дрели. Чаще всего ударный шум также возбуждает вибрации, распространяющиеся в виде структурного шума.

